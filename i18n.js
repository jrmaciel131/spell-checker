// Idioma da interface a partir do navegador (usado quando o usuário ainda não escolheu)
function detectUiLang() {
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'en-US';
  const l = nav.toLowerCase();
  if (l === 'pt-pt') return 'pt-PT';
  if (l.startsWith('pt')) return 'pt-BR';
  if (l.startsWith('es')) return 'es';
  if (l.startsWith('fr')) return 'fr';
  if (l === 'en-gb') return 'en-GB';
  return 'en-US';
}

// Retorna as traduções do idioma, completando chaves ausentes com o inglês
function getT(uiLang) {
  const lang = I18N[uiLang] ? uiLang : detectUiLang();
  const t = I18N[lang] || I18N_EN;
  return t === I18N_EN ? t : new Proxy(t, { get: (obj, key) => (key in obj ? obj[key] : I18N_EN[key]) });
}
